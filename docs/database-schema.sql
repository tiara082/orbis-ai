create index quality_investigations_batch_idx on quality_investigations (triggered_by_batch_id);
create index quality_investigations_fg_idx    on quality_investigations (triggered_by_fg_id);

-- daily 06:00 -> 06:00 period. Formula: X + L = Y + Z (+ co_product + loss)
create table volume_balance_periods (
  period_id       bigint generated always as identity primary key,
  period_start    timestamptz not null unique,             -- 06:00
  period_end      timestamptz not null,                    -- 06:00 next day
  opening_stock_l numeric(14,2) not null,                  -- X: sum of tank_current_states at period_start
  milk_in_l       numeric(14,2) not null,                  -- L: sum of unloading transfers
  premix_in_l     numeric(14,2) not null default 0,        -- non-milk 10% of flavoured products
  output_l        numeric(14,2) not null,                  -- Y: sum of finished_goods_batches.volume_filled_l
  closing_stock_l numeric(14,2) not null,                  -- Z: sum of tanks at period_end
  co_product_l    numeric(14,2) not null default 0,        -- cream from separators
  recorded_loss_l numeric(14,2) not null default 0,        -- QC samples, rejects, flush
  variance_l      numeric(14,2) generated always as (
                    opening_stock_l + milk_in_l + premix_in_l
                    - output_l - closing_stock_l - co_product_l - recorded_loss_l) stored,
  tolerance_l     numeric(14,2) not null default 0,
  balance_status  text not null default 'pending' check (balance_status in (
                    'pending', 'balanced', 'variance_detected')),
  check (period_end > period_start)
);

create table audit_events (
  audit_id           bigint generated always as identity primary key,
  entity_type        text not null check (entity_type in (
                       'tanker', 'lab_test', 'batch', 'transfer', 'genealogy', 'cip',
                       'fg_batch', 'schedule', 'recommendation', 'investigation', 'volume_balance')),
  entity_id          text not null,
  event_type         text not null check (event_type in (
                       'created', 'updated', 'approved', 'rejected', 'flagged', 'released', 'on_hold')),
  previous_hash      text,                                 -- current_hash of the prior row (null for genesis)
  current_hash       text not null unique,                 -- sha256(previous_hash || entity || snapshot || ts)
  actor_id           text not null,                        -- user id or 'system' / 'ai'
  occurred_at        timestamptz not null default now(),
  data_snapshot      jsonb not null
);
create index audit_events_entity_idx on audit_events (entity_type, entity_id);
create index audit_events_time_idx   on audit_events (occurred_at);


