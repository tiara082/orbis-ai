-- =============================================================================
-- ORBIS AI - Database Schema (Reference)
-- Greenfields Better Planning & Milk Volume Traceability
--
-- Target  : PostgreSQL 15+ / Supabase
-- Status  : Reference only. Prototype frontend uses hardcoded mock data;
--           this file is not executed by the app.
-- Scope   : Dairy milk products (plain = Full Cream / Skim / WC,
--           flavoured = Chocolate / Strawberry), raw milk as main material.
--
-- Layers
--   1. Master data        - seeded once from the provided CSV files
--   2. Numeric parameters - uploaded via Excel (CSV values are still "X")
--   3. Operational input  - uploaded via Excel each shift / day
--   4. Transactional      - written by the platform at runtime
--   5. AI, quality, audit - generated by the platform (incl. hash chain)
--
-- Conventions
--   - Natural text keys for master data (IDs come from plant CSVs).
--   - bigint identity keys for high-volume transactional tables.
--   - All timestamps are timestamptz. All volumes are liters (density 1 kg/L).
--   - Every foreign key column has an index.
-- =============================================================================


-- =============================================================================
-- LAYER 1 - MASTER DATA (source: *_1.csv)
-- =============================================================================

-- source: asset_configuration_1.csv (structural columns only)
create table assets (
  asset_id                  text primary key,              -- e.g. SFP-01, AT-03, FL-05
  asset_type                text not null,                 -- Unloading Bay, Raw Milk Tank, Sterilizer, ...
  asset_name                text not null,
  node_role                 text not null check (node_role in (
                              'process_asset', 'physical_pipe', 'logical_junction',
                              'material_source', 'delivery_source', 'finished_goods_sink')),
  compatible_product_family text[] not null default '{}',  -- e.g. {UHT,ESL,"UHT Skim"}; empty = any
  is_tank                   boolean not null default false -- true for RMT, SFP, CRT, PREMIX, MIX, AT
);

-- source: asset_connections_1.csv
create table asset_connections (
  connection_id        text primary key,                   -- e.g. GCON-104, CON-017
  source_asset_id      text not null references assets(asset_id),
  destination_asset_id text not null references assets(asset_id),
  via_asset_id         text references assets(asset_id),   -- dedicated pipe, e.g. PIPE-01
  flow_type            text not null check (flow_type in (
                         'main_milk', 'cream', 'premix', 'mixed_product',
                         'to_sterilization', 'sterilized_product', 'aseptic_supply', 'finished_goods')),
  max_flow_lph         numeric(12,2),                      -- "X" in CSV; filled via asset_parameters upload
  routing_condition    text
);
create index asset_connections_source_idx      on asset_connections (source_asset_id);
create index asset_connections_destination_idx on asset_connections (destination_asset_id);
create index asset_connections_via_idx         on asset_connections (via_asset_id);

-- source: pack_size_codes_1.csv
create table pack_sizes (
  pack_size_code text primary key,                         -- LARGE_A, LARGE_B, ESL_320, SMALL_A, SMALL_B
  description    text,
  exact_size_ml  integer not null check (exact_size_ml > 0)
);

-- source: market_variants_1.csv
create table market_variants (
  market_variant text primary key,                         -- LOCAL, EXP
  market_name    text not null
);

-- source: product_catalog_1.csv (liquid SKU)
create table products (
  sku_id         text primary key,                         -- e.g. UHT-FC, ESL-CH
  product_name   text not null,
  product_family text not null check (product_family in ('UHT', 'ESL', 'UHT Skim')),
  flavour        text not null,                            -- Full Cream, Chocolate, Strawberry, WC, Skim
  is_flavoured   boolean not null,                         -- true = Chocolate/Strawberry (rasa), false = plain
  milk_ratio     numeric(4,3) not null                     -- 1.000 plain, 0.900 flavoured (10% premix)
                 check (milk_ratio > 0 and milk_ratio <= 1)
);

-- source: finished_sku_catalog_1.csv
create table finished_skus (
  finished_sku_id text primary key,                        -- e.g. UHT-FC-1000-LOCAL
  liquid_sku_id   text not null references products(sku_id),
  pack_size_code  text not null references pack_sizes(pack_size_code),
  market_variant  text not null references market_variants(market_variant),
  unique (liquid_sku_id, pack_size_code, market_variant)
);
create index finished_skus_liquid_idx on finished_skus (liquid_sku_id);
create index finished_skus_pack_idx   on finished_skus (pack_size_code);
create index finished_skus_market_idx on finished_skus (market_variant);

-- source: line_dedication_1.csv + line_finished_sku_compatibility_1.csv
create table line_products (
  line_id                 text not null references assets(asset_id),       -- FL-01..FL-10
  finished_sku_id         text not null references finished_skus(finished_sku_id),
  source_aseptic_tank_id  text not null references assets(asset_id),       -- AT-01..AT-05
  eligible                boolean not null default true,
  primary key (line_id, finished_sku_id)
);
create index line_products_sku_idx on line_products (finished_sku_id);
create index line_products_at_idx  on line_products (source_aseptic_tank_id);

-- source: changeover_rules_1.csv
create table changeover_rules (
  rule_id         text primary key,                        -- VARIANT, SIZE, PAPER, NONE
  precedence      smallint not null unique,                -- 1 = FIRST ... 4 = LAST
  condition       text not null,
  activity        text not null,
  additional_note text
);

-- source: cip_rules_1.csv
create table cip_rules (
  rule_id     text primary key,                            -- CIP_FLAVOUR, CIP_CH_ST, CIP_END_PRODUCTION, CIP_EMPTY, CIP_DEDUP
  trigger     text not null,
  asset_scope text not null,
  requirement text not null
);

-- source: constraint_catalog_1.csv
create table constraint_catalog (
  rule_id     text primary key,                            -- e.g. CAPACITY, HOLDING, MASS_BALANCE
  scope       text not null,
  description text not null
);

-- not in CSV; uploaded via template_farms.csv
create table farms (
  farm_id   text primary key,                              -- e.g. FARM-01
  farm_name text not null,
  location  text,
  active    boolean not null default true
);


-- =============================================================================
-- LAYER 2 - NUMERIC PARAMETERS (source: template_asset_parameters.csv,
--                                       template_changeover_cip_durations.csv)
-- Versioned by effective_at so what-if simulations can reuse older values.
-- =============================================================================

create table asset_parameters (
  id                     bigint generated always as identity primary key,
  asset_id               text not null references assets(asset_id),
  capacity_l             numeric(12,2) check (capacity_l >= 0),
  min_operating_level_l  numeric(12,2) check (min_operating_level_l >= 0), -- e.g. AT ~50% for 2 fillers
  input_flow_lph         numeric(12,2) check (input_flow_lph >= 0),
  output_flow_lph        numeric(12,2) check (output_flow_lph >= 0),
  process_speed_lph      numeric(12,2) check (process_speed_lph >= 0),     -- not for filling lines
  speed_packph           numeric(12,2) check (speed_packph >= 0),          -- filling lines only
  holding_time_hours     numeric(6,2)  check (holding_time_hours >= 0),
  cip_duration_min       integer       check (cip_duration_min >= 0),
  utilization_target_pct numeric(5,2)  check (utilization_target_pct between 0 and 100), -- 90-95 target
  effective_at           timestamptz not null default now(),
  unique (asset_id, effective_at)
);
create index asset_parameters_asset_idx on asset_parameters (asset_id, effective_at desc);

create table changeover_durations (
  id           bigint generated always as identity primary key,
  rule_id      text not null references changeover_rules(rule_id),
  line_id      text references assets(asset_id),           -- null = applies to all lines
  duration_min integer not null check (duration_min >= 0), -- flavour change observed 15-60 min
  notes        text,
  effective_at timestamptz not null default now()
);
create index changeover_durations_rule_idx on changeover_durations (rule_id);
create index changeover_durations_line_idx on changeover_durations (line_id);

create table cip_durations (
  id           bigint generated always as identity primary key,
  rule_id      text not null references cip_rules(rule_id),
  asset_id     text references assets(asset_id),           -- null = applies to all assets in scope
  duration_min integer not null check (duration_min >= 0),
  effective_at timestamptz not null default now()
);
create index cip_durations_rule_idx  on cip_durations (rule_id);
create index cip_durations_asset_idx on cip_durations (asset_id);


-- =============================================================================
-- LAYER 3 - OPERATIONAL INPUT (source: Excel upload per shift / day)
-- =============================================================================

create table production_orders (
  order_id          text primary key,                      -- e.g. ORD-20261107-001
  finished_sku_id   text not null references finished_skus(finished_sku_id),
  volume_target_l   numeric(12,2) not null check (volume_target_l > 0),
  pack_count_target integer check (pack_count_target > 0), -- volume_target_l * 1000 / exact_size_ml
  deadline          timestamptz not null,
  priority          smallint not null default 2 check (priority between 1 and 3), -- 1 urgent
  status            text not null default 'pending' check (status in (
                      'pending', 'scheduled', 'in_progress', 'done', 'cancelled')),
  created_at        timestamptz not null default now()
);
create index production_orders_sku_idx    on production_orders (finished_sku_id);
create index production_orders_status_idx on production_orders (status, deadline);

create table tanker_deliveries (
  tanker_id      text primary key,                         -- delivery id from surat jalan, e.g. TRK-045
  farm_id        text not null references farms(farm_id),
  plate_number   text,
  volume_l       numeric(12,2) not null check (volume_l > 0),
  departure_time timestamptz not null,
  eta            timestamptz not null,
  actual_arrival timestamptz,
  bay_id         text references assets(asset_id),         -- UB-01..UB-04
  status         text not null default 'on_the_way' check (status in (
                   'on_the_way', 'arrived', 'sampling', 'lab_test', 'released',
                   'unloading', 'stored', 'rejected', 'delayed'))
);
create index tanker_deliveries_farm_idx   on tanker_deliveries (farm_id);
create index tanker_deliveries_bay_idx    on tanker_deliveries (bay_id);
create index tanker_deliveries_status_idx on tanker_deliveries (status, eta);

-- snapshot at shift start (06:00 opening stock for volume balance)
create table tank_current_states (
  id                  bigint generated always as identity primary key,
  asset_id            text not null references assets(asset_id),
  current_volume_l    numeric(12,2) not null check (current_volume_l >= 0),
  sku_id              text references products(sku_id),    -- null for raw / thermized milk
  material_state      text check (material_state in (
                        'raw', 'thermized', 'standardized', 'cream', 'premix', 'mixed', 'sterilized')),
  batch_id            text,                                -- FK added after batches table
  material_entry_time timestamptz,                         -- start of holding-time clock
  last_cip_completed  timestamptz,
  status              text not null check (status in (
                        'available', 'in_use', 'cip_required', 'in_cip', 'maintenance')),
  recorded_at         timestamptz not null default now()
);
create index tank_current_states_asset_idx on tank_current_states (asset_id, recorded_at desc);
create index tank_current_states_sku_idx   on tank_current_states (sku_id);
create index tank_current_states_batch_idx on tank_current_states (batch_id);

create table asset_availability_windows (
  id                bigint generated always as identity primary key,
  asset_id          text not null references assets(asset_id),
  unavailable_from  timestamptz not null,
  unavailable_until timestamptz not null,
  reason            text not null check (reason in ('cip', 'maintenance', 'trial', 'calibration', 'breakdown')),
  notes             text,
  check (unavailable_until > unavailable_from)
);
create index asset_availability_asset_idx on asset_availability_windows (asset_id, unavailable_from);


-- =============================================================================
-- LAYER 4 - TRANSACTIONAL (written by the platform at runtime)
-- Rule: 1 tank = 1 batch per production date (plant reference).
-- blockchain_hash = current_hash of the matching audit_events row.
-- =============================================================================

create table batches (
  batch_id        text primary key,                        -- e.g. B-20261107-SFP04-01
  asset_id        text not null references assets(asset_id),
  sku_id          text references products(sku_id),
  material_state  text not null check (material_state in (
                    'raw', 'thermized', 'standardized', 'cream', 'premix', 'mixed', 'sterilized')),
  tanker_id       text references tanker_deliveries(tanker_id), -- set for receiving batches
  production_date date not null,
  volume_l        numeric(12,2) not null check (volume_l >= 0),
  started_at      timestamptz not null default now(),          -- holding time counts from here
  status          text not null default 'active' check (status in (
                    'active', 'consumed', 'expired', 'on_hold', 'released', 'rejected')),
  created_at      timestamptz not null default now(),
  blockchain_hash text
);
create index batches_asset_idx  on batches (asset_id, production_date);
create index batches_sku_idx    on batches (sku_id);
create index batches_tanker_idx on batches (tanker_id);
create index batches_status_idx on batches (status);

alter table tank_current_states
  add constraint tank_current_states_batch_fk foreign key (batch_id) references batches(batch_id);

-- every physical movement of material; source of genealogy edges
create table batch_transfers (
  transfer_id          bigint generated always as identity primary key,
  source_batch_id      text not null references batches(batch_id),
  dest_batch_id        text not null references batches(batch_id),
  via_connection_id    text references asset_connections(connection_id),
  volume_transferred_l numeric(12,2) not null check (volume_transferred_l > 0),
  transfer_start       timestamptz not null,
  transfer_end         timestamptz,
  event_type           text not null check (event_type in (
                         'unloading', 'transfer', 'processing', 'separation',
                         'mixing', 'splitting', 'sterilization', 'filling')),
  operator_id          text,
  notes                text,
  blockchain_hash      text,
  check (source_batch_id <> dest_batch_id),
  check (transfer_end is null or transfer_end >= transfer_start)
);
create index batch_transfers_source_idx     on batch_transfers (source_batch_id);
create index batch_transfers_dest_idx       on batch_transfers (dest_batch_id);
create index batch_transfers_connection_idx on batch_transfers (via_connection_id);
create index batch_transfers_time_idx       on batch_transfers (transfer_start);

-- aggregated parent/child edges used by backward & forward trace
create table batch_genealogy (
  child_batch_id        text not null references batches(batch_id),
  parent_batch_id       text not null references batches(batch_id),
  volume_contribution_l numeric(12,2) not null check (volume_contribution_l > 0),
  contribution_pct      numeric(5,2) check (contribution_pct between 0 and 100),
  relation_type         text not null check (relation_type in ('transfer', 'mixing', 'splitting', 'co_product')),
  primary key (child_batch_id, parent_batch_id),
  check (child_batch_id <> parent_batch_id)
);
create index batch_genealogy_parent_idx on batch_genealogy (parent_batch_id);

create table lab_tests (
  test_id           bigint generated always as identity primary key,
  tanker_id         text not null references tanker_deliveries(tanker_id),
  sample_taken_at   timestamptz not null,
  test_completed_at timestamptz,
  result            text not null default 'pending' check (result in ('pending', 'pass', 'fail')),
  parameters        jsonb,                                 -- fat, protein, acidity, TPC, antibiotic, ...
  release_status    text not null default 'pending' check (release_status in (
                      'pending', 'released', 'rejected', 'on_hold')),
  analyst_id        text,
  blockchain_hash   text
);
create index lab_tests_tanker_idx on lab_tests (tanker_id);

create table cip_events (
  cip_event_id     bigint generated always as identity primary key,
  asset_id         text not null references assets(asset_id),
  rule_id          text not null references cip_rules(rule_id),
  related_batch_id text references batches(batch_id),
  start_time       timestamptz not null,
  end_time         timestamptz,
  status           text not null default 'scheduled' check (status in (
                     'scheduled', 'in_progress', 'completed', 'cancelled')),
  operator_id      text,
  blockchain_hash  text
);
create index cip_events_asset_idx on cip_events (asset_id, start_time);
create index cip_events_rule_idx  on cip_events (rule_id);
create index cip_events_batch_idx on cip_events (related_batch_id);

create table production_schedule_runs (
  run_id                    bigint generated always as identity primary key,
  production_order_id       text not null references production_orders(order_id),
  filling_line_id           text references assets(asset_id),
  asset_sequence            jsonb not null,                -- [{asset_id, start, end, batch_id}] RMT->TH->SFP->ST->AT->FL
  scheduled_start           timestamptz not null,
  scheduled_end             timestamptz not null,
  changeover_min            integer not null default 0,
  cip_min                   integer not null default 0,
  ai_recommended            boolean not null default false,
  recommendation_id         bigint,                        -- FK added after ai_recommendations
  estimated_output_l        numeric(12,2),
  estimated_utilization_pct numeric(5,2),
  status                    text not null default 'draft' check (status in (
                              'draft', 'approved', 'rejected', 'running', 'done', 'superseded')),
  approved_by               text,
  approved_at               timestamptz,
  rejection_reason          text,
  check (scheduled_end > scheduled_start)
);
create index schedule_runs_order_idx on production_schedule_runs (production_order_id);
create index schedule_runs_line_idx  on production_schedule_runs (filling_line_id, scheduled_start);
create index schedule_runs_rec_idx   on production_schedule_runs (recommendation_id);

create table finished_goods_batches (
  fg_batch_id         text primary key,                    -- e.g. FG-20261107-FL05-01
  liquid_batch_id     text not null references batches(batch_id), -- aseptic tank batch
  finished_sku_id     text not null references finished_skus(finished_sku_id),
  filling_line_id     text not null references assets(asset_id),
  production_order_id text references production_orders(order_id),
  schedule_run_id     bigint references production_schedule_runs(run_id),
