  traced_batches          jsonb not null default '[]',     -- batches pulled from genealogy as context
  recommended_plan        jsonb not null,                  -- proposed schedule runs
  reasoning               text not null,
  expected_utilization_pct numeric(5,2),
  expected_recovery_min   integer,
