// Generates docs/USER_GUIDE.md from src/content/userGuide.ts (Node 22.18+ strips the TypeScript types).
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { GUIDE_META, GUIDE_SECTIONS, QUICK_START } from '../src/content/userGuide.ts'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(rootDir, 'docs', 'USER_GUIDE.md')

const HIGHLIGHT = { ai: 'Fokus AI', trace: 'Fokus Ketertelusuran' }
const CALLOUT = { brand: 'TIP', info: 'NOTE', success: 'TIP', warning: 'WARNING', danger: 'CAUTION' }

const cell = (text) => text.replace(/\|/g, '\\|')
const mermaidLabel = (text) => text.replace(/"/g, '#quot;')

function table(head, rows) {
  return [`| ${head.map(cell).join(' | ')} |`, `|${head.map(() => ' --- ').join('|')}|`, ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`)].join('\n')
}

function block(b) {
  switch (b.type) {
    case 'heading':
      return `### ${b.text}`
    case 'p':
      return b.text
    case 'list':
      return b.items.map((item) => `- ${item}`).join('\n')
    case 'steps':
      return b.items.map((item, i) => `${i + 1}. ${item}`).join('\n')
    case 'callout':
      return [`> [!${CALLOUT[b.tone]}]`, `> **${b.title}**`, `> ${b.text}`].join('\n')
    case 'table':
      return table(b.head, b.rows)
    case 'flow': {
      const nodes = b.items.map((item, i) => `  n${i}["${mermaidLabel(item.detail ? `${item.label}: ${item.detail}` : item.label)}"]`)
      const edges = b.items.slice(1).map((_, i) => `  n${i} --> n${i + 1}`)
      return ['```mermaid', 'flowchart LR', ...nodes, ...edges, '```'].join('\n')
    }
    case 'links':
      return `Buka di aplikasi: ${b.items.map((item) => `${item.label} (\`${item.path}\`)`).join(' · ')}`
    case 'faq':
      return b.items.map((item) => `**${item.q}**\n${item.a}`).join('\n\n')
    case 'widget':
      return ''
    default:
      throw new Error(`Unknown guide block: ${b.type}`)
  }
}

const anchor = (title) =>
  title
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s+/g, '-')

const parts = [
  '<!-- Generated by scripts/build_user_guide.js from src/content/userGuide.ts. Edit the source, then run `npm run guide:md`. -->',
  `# ${GUIDE_META.title}`,
  `_${GUIDE_META.subtitle}_`,
  GUIDE_META.intro,
  `> ${GUIDE_META.demoNote}`,
  'Panduan yang sama tersedia di dalam aplikasi: klik avatar di pojok kanan atas, lalu pilih **Panduan Pengguna** (`/guide`).',
  '## Mulai cepat',
  QUICK_START.map((step, i) => {
    const section = GUIDE_SECTIONS.find((s) => s.id === step.sectionId)
    return `${i + 1}. **${step.label}**: ${step.detail} ([${section.title}](#${anchor(section.title)}))`
  }).join('\n'),
  '## Daftar isi',
  GUIDE_SECTIONS.map((s) => `- [${s.title}](#${anchor(s.title)})${s.highlight ? ` · _${HIGHLIGHT[s.highlight]}_` : ''}`).join('\n'),
  ...GUIDE_SECTIONS.flatMap((s) => [
    '---',
    `## ${s.title}`,
    s.highlight ? `**${HIGHLIGHT[s.highlight]}** · ${s.summary}` : `_${s.summary}_`,
    ...s.blocks.map(block).filter(Boolean)
  ])
]

fs.writeFileSync(outFile, `${parts.join('\n\n')}\n`)
console.log(`Wrote ${path.relative(rootDir, outFile)}`)
